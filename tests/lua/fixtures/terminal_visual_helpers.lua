local PALETTE = {
    bg = { 14, 18, 27 },
    panel = { 22, 27, 39 },
    panel2 = { 29, 35, 50 },
    edge = { 78, 88, 112 },
    title = { 238, 242, 255 },
    dim = { 145, 156, 178 },
    text = { 218, 226, 240 },
    prompt = { 74, 222, 222 },
    ok = { 72, 211, 134 },
    warn = { 246, 196, 83 },
    error = { 255, 104, 104 },
    accent = { 139, 161, 255 },
    magenta = { 218, 132, 255 },
}

local function color(name)
    return PALETTE[name or "text"] or PALETTE.text
end

local function draw_text(img, x, y, text, color_name, scale)
    scale = scale or 2
    local c = color(color_name)
    local s = tostring(text or ""):upper()
    local pen = x
    for i = 1, #s do
        local ch = s:sub(i, i)
        local glyph = FONT[ch] or FONT["?"]
        for gy = 1, 7 do
            local row = glyph[gy]
            for gx = 1, 5 do
                if row:sub(gx, gx) == "1" then
                    img:drawRect(pen + (gx - 1) * scale, y + (gy - 1) * scale, scale, scale, c[1], c[2], c[3], 255)
                end
            end
        end
        pen = pen + 6 * scale
    end
end

local function draw_outline(img, x, y, w, h, color_name)
    local c = color(color_name or "edge")
    img:drawLine(x, y, x + w, y, c[1], c[2], c[3], 255)
    img:drawLine(x + w, y, x + w, y + h, c[1], c[2], c[3], 255)
    img:drawLine(x + w, y + h, x, y + h, c[1], c[2], c[3], 255)
    img:drawLine(x, y + h, x, y, c[1], c[2], c[3], 255)
end

function terminal_visual.save(path, spec)
    local width = spec.width or 1120
    local height = spec.height or 420
    local img = lurek.image.newImageData(width, height)
    local bg = color("bg")
    local panel = color("panel")
    local panel2 = color("panel2")
    img:drawRect(0, 0, width, height, bg[1], bg[2], bg[3], 255)
    img:drawRect(0, 0, width, 34, panel[1], panel[2], panel[3], 255)
    img:drawCircle(20, 17, 6, 255, 96, 92, 255)
    img:drawCircle(42, 17, 6, 246, 196, 83, 255)
    img:drawCircle(64, 17, 6, 72, 211, 134, 255)
    draw_text(img, 88, 10, spec.title or "TERMINAL", "title", 2)
    img:drawRect(18, 54, width - 36, height - 74, panel2[1], panel2[2], panel2[3], 255)
    draw_outline(img, 18, 54, width - 36, height - 74, "edge")

    local y = 76
    for _, line in ipairs(spec.lines or {}) do
        if line.rule then
            local c = color(line.color or "edge")
            img:drawLine(38, y + 6, width - 42, y + 6, c[1], c[2], c[3], 255)
        else
            draw_text(img, 38 + (line.indent or 0), y, line.text or "", line.color or "text", line.scale or 2)
        end
        y = y + (line.gap or 20)
    end

    if spec.footer then
        img:drawRect(18, height - 30, width - 36, 18, panel[1], panel[2], panel[3], 255)
        draw_text(img, 38, height - 25, spec.footer, "dim", 2)
    end

    lurek.image.savePNG(img, path)
end
