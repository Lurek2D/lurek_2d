mod heightmap_tests {
    use super::*;

    #[test]
    fn get_clamps_oob() {
        let hm = Heightmap::generate(&HeightmapOpts {
            width: 4,
            height: 4,
            ..Default::default()
        });
        let _ = hm.get(100, 100); // should not panic
    }

    #[test]
    fn erosion_keeps_normalised() {
        let hm = Heightmap::generate(&HeightmapOpts {
            erosion_passes: 3,
            ..Default::default()
        });
        for &v in &hm.cells {
            assert!(
                (0.0..=1.0).contains(&v),
                "post-erosion value out of [0,1]: {v}"
            );
        }
    }

    #[test]
    fn to_rgba_bytes_length() {
        let hm = Heightmap::generate(&HeightmapOpts {
            width: 4,
            height: 4,
            ..Default::default()
        });
        assert_eq!(hm.to_rgba_bytes().len(), 4 * 4 * 4);
    }
}

