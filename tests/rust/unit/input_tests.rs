mod combo_tests {
    use super::*;

    fn make_steps() -> Vec<ComboStep> {
        vec![
            ComboStep {
                key: "down".into(),
                max_gap_ms: 500,
            },
            ComboStep {
                key: "right".into(),
                max_gap_ms: 500,
            },
            ComboStep {
                key: "a".into(),
                max_gap_ms: 500,
            },
        ]
    }

    #[test]
    fn empty_combo_is_idle() {
        let mut d = ComboDetector::new(vec![], 1000);
        assert!(d.is_empty());
        assert_eq!(d.feed("a", 0), ComboProgress::Idle);
    }

    #[test]
    fn disabled_returns_idle() {
        let mut d = ComboDetector::new(make_steps(), 2000);
        d.enabled = false;
        assert_eq!(d.feed("down", 0), ComboProgress::Idle);
    }

    #[test]
    fn combo_detector_saturates_large_elapsed() {
        let mut detector = ComboDetector::new(
            vec![
                ComboStep {
                    key: "down".into(),
                    max_gap_ms: u64::MAX,
                },
                ComboStep {
                    key: "right".into(),
                    max_gap_ms: u64::MAX,
                },
                ComboStep {
                    key: "a".into(),
                    max_gap_ms: u64::MAX,
                },
            ],
            u64::MAX,
        );
        assert_eq!(
            detector.feed("down", u64::MAX),
            ComboProgress::Advanced { step: 1, total: 3 }
        );
        assert_eq!(
            detector.feed("right", u64::MAX),
            ComboProgress::Advanced { step: 2, total: 3 }
        );
        assert_eq!(
            detector.tick(u64::MAX),
            ComboProgress::Advanced { step: 2, total: 3 }
        );
    }

    #[test]
    fn combo_detector_normalizes_alias_keys() {
        let mut detector = ComboDetector::new(
            vec![
                ComboStep {
                    key: "enter".into(),
                    max_gap_ms: 100,
                },
                ComboStep {
                    key: "esc".into(),
                    max_gap_ms: 100,
                },
            ],
            500,
        );
        assert_eq!(
            detector.feed("return", 0),
            ComboProgress::Advanced { step: 1, total: 2 }
        );
        assert_eq!(detector.feed("escape", 0), ComboProgress::Completed);
    }
}

